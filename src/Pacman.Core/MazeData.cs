    public static bool IsWall(int gridX, int gridY)
    {
        if (gridX < 0 || gridX >= Width || gridY < 0 || gridY >= Height)
            return false;
        return Grid[gridY, gridX] == 1;
    }

    public static bool IsWalkable(int gridX, int gridY, bool isGhost = false)
    {
        if (gridX < 0 || gridX >= Width || gridY < 0 || gridY >= Height)
            return true;
        int cell = Grid[gridY, gridX];
        if (cell == 1) return false;
        if (cell == 4 && !isGhost) return false;
        return true;
    }

    public static int GetCell(int gridX, int gridY)
    {
        if (gridX < 0 || gridX >= Width || gridY < 0 || gridY >= Height)
            return 0;
        return Grid[gridY, gridX];
    }
